import { assertResultNotAborted, type ResultDiagnostic, type ResultInputFile, type ResultReadOptions } from './contracts';
import { emptyScientificData, emptyScientificDiagnostics, scientificNumber, type NebAuxiliaryData, type ScientificField } from './scientific-contracts';
import { readAuxiliarySourceLines } from './auxiliary-source-lines';

const kindOf = (text: string): NebAuxiliaryData['kind'] | null => /^NEB log file generated by ORCA\s*\r?\n/.test(text.replace(/^\uFEFF/, '')) ? 'log'
  : /^\s*Iteration:\s*\d+\s*\r?\nImages:\s*Distance\s+\(Bohr\),\s*Energy\s+\(Eh\)/.test(text.replace(/^\uFEFF/, '')) ? 'interpolation' : null;
const tokens = (text: string) => text.trim().split(/\s+/);

/** Narrow native tables. An interpolation grammar alone does not identify its producer/job. */
export function parseNebAuxiliary(text: string | readonly string[], kind: NebAuxiliaryData['kind'], source: NebAuxiliaryData['source']): NebAuxiliaryData {
  const data: NebAuxiliaryData = { kind, source, status: 'complete', messages: [], iterations: [] };
  const lines = typeof text === 'string' ? text.replace(/^\uFEFF/, '').split(/\r?\n/) : text;
  let observed = 0;
  const partial = (message: string) => { data.status = 'partial'; if (!data.messages.includes(message)) data.messages.push(message); };
  const admit = (count: number) => { observed += count; return true; };
  const numeric = (raw: string) => { const row = tokens(raw); return row.length && row.every(token => scientificNumber(token) !== null) ? row : null; };
  let pending: { iteration: number; sourceLine: number; count?: number; distances?: string[]; energies?: string[]; energyLine?: number; forces: ScientificField[][] } | null = null;
  let imageRows: NebAuxiliaryData['iterations'][number]['images'] | null = null;
  let interpolationIteration = -1, interpolationLine = 0;
  const flushLog = () => {
    if (!pending) return;
    const p = pending; pending = null;
    if (!p.count || !Number.isSafeInteger(p.count) || p.count < 3 || p.distances?.length !== p.count || p.energies?.length !== p.count || !p.energyLine) { partial(`源行${p.sourceLine}的NEB log块不完整，未补造image。`); return; }
    if (!admit(p.count * 2)) return;
    data.iterations.push({ iteration: p.iteration, sourceLine: p.sourceLine, images: p.distances.map((distanceRaw, image) => ({ image, distanceRaw, distanceBohr: scientificNumber(distanceRaw)!, energy: { kind: 'neb-log', value: scientificNumber(p.energies![image])!, rawValue: p.energies![image], unit: 'hartree', source: { id: source.id, name: source.name, line: p.energyLine! }, iteration: p.iteration, image, association: 'native-table', origin: 'observation' }, ...(p.forces[image]?.length ? { forces: p.forces[image] } : {}) })) });
  };
  const flushInterp = () => {
    if (imageRows && imageRows.length >= 3) data.iterations.push({ iteration: interpolationIteration, sourceLine: interpolationLine, images: imageRows });
    else if (imageRows) partial(`源行${interpolationLine}的Images表不完整。`);
    imageRows = null;
  };
  const atomicUnits = kind !== 'log' || lines.some(line => /^All quantities are given in atomic units\. Unless stated otherwise\.\s*$/.test(line));
  if (!atomicUnits) { partial('NEB log未确认原生atomic-units声明，未认证表中单位。'); return data; }
  for (let index = 0; index < lines.length; index++) {
    const line = lines[index], sourceLine = index + 1;
    if (line.includes('\0')) { partial(`源行${sourceLine}含NUL损坏，停止并保完整前缀。`); break; }
    if (kind === 'interpolation') {
      const iteration = line.match(/^Iteration:\s*(\d+)\s*$/);
      if (iteration) { flushInterp(); interpolationIteration = Number(iteration[1]); interpolationLine = sourceLine; if (!Number.isSafeInteger(interpolationIteration)) { partial('NEB迭代标识超出整数范围。'); break; } continue; }
      if (/^Images:\s*Distance\s+\(Bohr\),\s*Energy\s+\(Eh\)\s*$/.test(line) && interpolationIteration >= 0) { imageRows = []; continue; }
      if (!imageRows) continue;
      const row = numeric(line);
      if (!row || row.length !== 3) { flushInterp(); continue; }
      if (!admit(2)) { imageRows = null; break; }
      const image = imageRows.length;
      imageRows.push({ image, distanceRaw: row[1], distanceBohr: scientificNumber(row[1])!, relativeEnergy: { kind: 'neb-interpolation', value: scientificNumber(row[2])!, rawValue: row[2], unit: 'hartree', relative: true, source: { id: source.id, name: source.name, line: sourceLine }, iteration: interpolationIteration, image, association: 'native-table', origin: 'observation' } });
    } else {
      const iteration = line.match(/^iteration\s*:\s*(\d+)\s*$/);
      if (iteration) { flushLog(); const value = Number(iteration[1]); if (!Number.isSafeInteger(value)) { partial('NEB迭代标识超出整数范围。'); break; } pending = { iteration: value, sourceLine, forces: [] }; continue; }
      if (!pending) continue;
      const count = line.match(/^nim\s*:\s*(\d+)\s*$/); if (count) { pending.count = Number(count[1]); continue; }
      const array = line.match(/^(distance|energy|max\(\|Fr_perp\|\)|Fr_paral|max\(\|Fsp_paral\|\)|max\(\|Fsp_perp\|\)|max\(\|FNEB\|\)|max\(\|Force\|\)|max\(\|step\|\))\s*:\s*(.*?)\s*$/);
      if (!array) continue;
      const row = numeric(array[2]);
      if (!row || !pending.count || row.length !== pending.count) { partial(`源行${sourceLine}数组计数或数值损坏，未将该块认证完整。`); pending.count = undefined; continue; }
      if (array[1] === 'distance') pending.distances = row;
      else if (array[1] === 'energy') { pending.energies = row; pending.energyLine = sourceLine; }
      else if (admit(row.length)) row.forEach((token, image) => { (pending!.forces[image] ??= []).push({ key: array[1], label: array[1], value: scientificNumber(token)!, rawValue: token, sourceLine, sourceId: source.id, sourceName: source.name, unit: array[1] === 'max(|step|)' ? 'bohr' : 'hartree/bohr', origin: 'observation', frameIndex: null }); });
    }
  }
  if (kind === 'log') flushLog(); else flushInterp();
  if (!data.iterations.length) partial('没有完整的NEB辅助迭代块；原始来源仍独立保留。');
  return data;
}

export interface NebAuxiliarySource { data: NebAuxiliaryData; diagnostic: ResultDiagnostic; retainedBytes: number }
export async function readNebAuxiliary(file: ResultInputFile, options: ResultReadOptions = {}, _retentionLimit?: number): Promise<NebAuxiliarySource | null> {
  let bytes: Uint8Array | undefined, closed = false, sourceClosed = false;
  const closeSource = async () => { if (sourceClosed) return; sourceClosed = true; await file.close?.(); };
  let prefix: Uint8Array;
  try {
    assertResultNotAborted(options.signal);
    const prefixLength = Math.min(file.size, 65536); prefix = await file.readRange(0, prefixLength, options.signal);
    assertResultNotAborted(options.signal);
    if (prefix.length !== prefixLength) throw new Error('NEB辅助候选前缀读取长度发生变化。');
  } catch (error) { await closeSource(); throw error; }
  const kind = kindOf(new TextDecoder().decode(prefix)); if (!kind) return null;
  const source: NebAuxiliaryData['source'] = { id: file.id, name: file.name, size: file.size };
  let data: NebAuxiliaryData;
  try {
    const read = await readAuxiliarySourceLines(file, options, prefix);
    source.sha256 = read.sha256;
    data = parseNebAuxiliary(read.lines, kind, source);
    if (read.interruption) { data.status = 'partial'; data.messages.push(read.interruption); }
  } catch (error) { await closeSource(); throw error; }
  const scientific = emptyScientificData(); scientific.diagnostics = emptyScientificDiagnostics();
  scientific.notices.push(...data.messages);
  scientific.nebEvidence = { version: '', association: [], auxiliaries: [data], conflicts: [], geometryMapped: 0, geometryTotal: 0, energyMapped: 0 };
  const diagnostic: ResultDiagnostic = { kind: 'diagnostic', id: `${file.id}:neb-auxiliary`, label: `${file.name} · NEB辅助来源`, engine: kind === 'log' ? 'orca' : 'unknown', sourceRole: 'auxiliary', source: { id: file.id, name: file.name, size: file.size, software: kind === 'log' ? 'orca' : 'unknown' }, jobIndex: null, segmentIndex: 0, charge: null, multiplicity: null, status: data.status === 'partial' ? 'incomplete' : 'unknown', messages: [...data.messages, '辅助表不含可独立认证的结构/作业；未生成零原子模型。'], scientific,
    async readSourceRange(start, end, signal) {
      assertResultNotAborted(signal); if (closed) throw new Error('NEB辅助来源已关闭。');
      if (![start, end].every(Number.isSafeInteger) || start < 0 || end < start || end > file.size || end - start > 64 * 1024 ** 2) throw new Error('NEB辅助来源范围无效。');
      const read = bytes ? bytes.slice(start, end) : await file.readRange(start, end, signal);
      assertResultNotAborted(signal); if (closed || read.length !== end - start) throw new Error('NEB辅助来源关闭或长度发生变化。'); return read;
    }, async dispose() { if (closed) return; closed = true; bytes = undefined; await closeSource(); },
  };
  return { data, diagnostic, retainedBytes: bytes?.byteLength ?? 0 };
}
