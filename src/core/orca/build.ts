import { getOrcaMethodProfile } from './catalog';
import { mergeOrcaScfBlocks, normalizeOrcaScientificKeywords, orcaReferenceKeywords, renderOrcaHeader } from './header';
import { renderOrcaTask } from './tasks';
import { renderOrcaWorkflow } from './workflows';
import { renderOrcaMultiscale } from './multiscale';
import { validateOrca } from './validation';
import { projectOrcaFreezeSettings } from '../input-freezes';
import type { OrcaBuildResult, OrcaJobRequest, OrcaOutputFile, OrcaRenderContext, OrcaTaskVariant, OrcaVersion } from './types';

export function buildOrca(req: OrcaJobRequest, assetTargetVersion: OrcaVersion = req.settings.version): OrcaBuildResult {
  // Consumer-only master gate precedes reference validation and every workflow.
  req = { ...req, settings: projectOrcaFreezeSettings(req.settings) };
  const issues = validateOrca(req, assetTargetVersion);
  const result: OrcaBuildResult = { files: [], issues, preview: '', version: req.settings.version };
  const method = getOrcaMethodProfile(req.settings.method, req.settings.version);
  if (issues.some(issue => issue.severity === 'error') || !method || !req.structure) return result;
  const s = req.settings;
  const ctx: OrcaRenderContext = {
    stem: req.name, method: s.multiscale.mode === 'none' ? method : { ...method, frequency: 'numeric' },
    atomIndex: id => req.structure!.atoms.findIndex((atom, index) => (atom.id ?? `atom-${index + 1}`) === id),
    asset: (id, kind) => req.assets.find(asset => asset.id === id && asset.kind === kind),
  };
  const task = ['neb', 'esd', 'md'].includes(s.task) ? renderOrcaWorkflow(req, ctx) : renderOrcaTask(req, ctx);
  const multiscale = renderOrcaMultiscale(req, ctx);
  issues.push(...task.issues, ...multiscale.issues);
  const header = renderOrcaHeader(req, method);
  const common = header.keywords, blocks = header.blocks;
  issues.push(...header.issues);
  if (issues.some(issue => issue.severity === 'error')) return result;
  const coordinates = req.structure.atoms.map(atom => `${atom.element} ${atom.x.toFixed(10)} ${atom.y.toFixed(10)} ${atom.z.toFixed(10)}`);
  const variants: OrcaTaskVariant[] = task.variants ?? [{ suffix: '' }];
  const files: OrcaOutputFile[] = [];
  for (const variant of variants) {
    const name = `${req.name}${variant.suffix ? `-${variant.suffix}` : ''}.inp`;
    const title = 'Generated by Ester Studio';
    const effectiveMultiplicity = variant.multiplicity ?? (s.multiscale.mode === 'none' ? req.multiplicity : s.multiscale.qmMultiplicity);
    const effectiveCharge = variant.charge ?? (s.multiscale.mode === 'none' ? req.charge : s.multiscale.qmCharge);
    const reference = orcaReferenceKeywords(req, method, effectiveMultiplicity);
    const keywords = normalizeOrcaScientificKeywords([...common, ...reference, ...multiscale.keywords, ...(variant.keywords ?? task.keywords)], s);
    const before = mergeOrcaScfBlocks([...blocks, ...multiscale.blocksBeforeCoordinates, ...(variant.blocksBeforeCoordinates ?? task.blocksBeforeCoordinates)]);
    const after = [...(variant.blocksAfterCoordinates ?? task.blocksAfterCoordinates), ...multiscale.blocksAfterCoordinates];
    const text = [title ? `# ${title}` : '', `! ${keywords.join(' ')}`, `%pal nprocs ${req.cores} end`, `%maxcore ${Math.floor(req.memoryGB * (768 / req.cores))}`, ...before, `* xyz ${effectiveCharge} ${effectiveMultiplicity}`, ...(variant.coordinateLines ?? multiscale.coordinateLines ?? task.coordinateLines ?? coordinates), '*', ...after, '', ''].filter((line, index) => index !== 0 || !!line).join('\n');
    files.push({ name, text, role: 'input' });
  }
  files.push(...task.files, ...multiscale.files);
  const seen = new Set<string>();
  const outputStems = files.filter(file => file.role === 'input').map(file => file.name.slice(0, -4).toLowerCase());
  if (req.assets.some(asset => outputStems.some(stem => asset.name.toLowerCase().startsWith(`${stem}.`)))) issues.push({ field: 'assets', severity: 'error', message: '依赖文件与独立子任务输出同名，可能被覆盖。' });
  for (const file of files) {
    const normalized = file.name.toLowerCase();
    if (seen.has(normalized)) issues.push({ field: 'files', severity: 'error', message: `输出文件名称冲突：${file.name}` });
    seen.add(normalized);
  }
  if (issues.some(issue => issue.severity === 'error')) return result;
  result.files = files;
  result.preview = files.filter(file => file.role === 'input').map(file => files.filter(item => item.role === 'input').length > 1 ? `# FILE: ${file.name}\n${file.text}` : file.text).join('\n');
  return result;
}
