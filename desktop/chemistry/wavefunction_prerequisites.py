"""Validate native xTB valence/EDF readback without inventing spin or core MOs."""
import math
import re
from orbitals import OrbitalError

NUMBER = r'[+-]?(?:\d+(?:\.\d*)?|\.\d+)(?:[dDeE][+-]?\d+)?'

def xtb_native_prerequisites(metadata, output, trusted=None, require_total_density=True):
    recognized = bool(re.search(r'This file is found to be generated by xtb! Special treatment is applied', output, re.I))
    if not recognized:
        if trusted is not None:
            raise OrbitalError('analysis-xtb-source', 'Multiwfn did not recognize the authenticated xTB Molden; no valence/core convention was assumed.')
        return None
    if metadata.get('format') != 'molden':
        raise OrbitalError('analysis-xtb-source', 'Native xTB recognition conflicts with the source format.')
    electron = re.search(r'Total/Alpha/Beta electrons:\s*('+NUMBER+r')', output)
    charge = re.search(r'Net charge:\s*('+NUMBER+r')', output)
    if not electron or not charge:
        raise OrbitalError('analysis-xtb-electrons', 'Native xTB electron and charge readback is incomplete.')
    numeric = lambda token: float(token.replace('D','E').replace('d','e'))
    represented = sum(row['occupation'] for row in metadata['orbitals'])
    native_electrons, net_charge = numeric(electron[1]), numeric(charge[1])
    if not math.isfinite(represented) or abs(native_electrons-represented) > .001 or abs(net_charge-round(net_charge)) > .001:
        raise OrbitalError('analysis-xtb-electrons', 'Native xTB electron/charge readback disagrees with source MO occupations.')
    physical = sum(atom['atomicNumber'] for atom in metadata['atoms'])-round(net_charge)
    core = physical-represented
    if core < -.001 or abs(core-round(core)) > .001:
        raise OrbitalError('analysis-xtb-core', 'Native xTB physical and represented electron counts have no valid core difference.')
    edf_complete = core <= .001
    if core > .001:
        total = re.search(r'The number of total inner-core electrons:\s*(\d+)', output)
        atomic = [int(value) for value in re.findall(r'Core electrons:\s*(\d+)\s+EDF primitive GTFs:', output)]
        edf_complete = bool(total and int(total[1]) == round(core) and sum(atomic) == round(core) and 'Loading EDF library finished!' in output)
        if require_total_density and not edf_complete:
            raise OrbitalError('analysis-xtb-core', 'Native xTB EDF core completion is missing or inconsistent; this method needs a verified total density.')
    if trusted is not None and (abs(net_charge-trusted['charge'])>.001 or abs(physical-trusted['physicalElectronCount'])>.001):
        raise OrbitalError('analysis-xtb-electrons', 'Native xTB charge/core readback conflicts with the authenticated request.')
    return dict(sourceRepresentation='xtb-valence-molden', sourceSpinResolution='spin-summed', independentAlphaBeta=False,
                nativeRepresentedElectronCount=represented, coreElectronCount=round(core), nativePhysicalElectronCount=physical,
                nativeNetCharge=round(net_charge), nativeDensityRepresentation=('edf-core-completed' if edf_complete else 'valence-only') if core>.001 else 'all-represented-electrons')
