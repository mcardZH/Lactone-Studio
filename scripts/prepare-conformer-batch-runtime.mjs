// Static desktop consumer of the existing scientific acceptance authority.
// Shipping this output requires neither a TS loader nor a runtime bundler.
import { rolldown } from 'rolldown';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve, relative } from 'node:path';
import { createHash } from 'node:crypto';
const root = resolve(import.meta.dirname, '..');
const entry = 'es-conformer-batch-science-entry';
const bundle = await rolldown({ cwd: root, input: entry, platform: 'node', plugins: [{
  name: 'same-source-conformer-science',
  resolveId(id) { if (id === entry) return '\0' + entry; },
  load(id) { if (id === '\0' + entry) return `export { createAdvancedForcefieldAdapter } from ${JSON.stringify(resolve(root, 'src/modeling/advanced/forcefield-adapter.ts').replaceAll('\\', '/'))};\nexport { validateAdvancedXtbResult } from ${JSON.stringify(resolve(root, 'src/modeling/advanced/xtb-result.ts').replaceAll('\\', '/'))};\nexport { effectiveSharedFreezes } from ${JSON.stringify(resolve(root, 'src/modeling/constraints.ts').replaceAll('\\', '/'))};`; },
}] });
try {
  const { output } = await bundle.generate({ format: 'cjs', sourcemap: false, minify: false });
  if (output.length !== 1 || output[0].type !== 'chunk' || output[0].imports.length) throw Error('Scientific desktop adapter must be one self-contained CJS file');
  const sources = [];
  for (const file of Object.keys(output[0].modules).filter(file => !file.startsWith('\0')).sort()) sources.push({ path: relative(root, file).replaceAll('\\', '/'), sha256: createHash('sha256').update(await readFile(file)).digest('hex') });
  const code = '// Generated by scripts/prepare-conformer-batch-runtime.mjs; single scientific source authority.\n// Sources: ' + JSON.stringify(sources) + '\n' + output[0].code.replaceAll('\r\n', '\n');
  await writeFile(resolve(root, 'desktop/conformer-batch-science-runtime.cjs'), code, 'utf8');
  console.log(`Prepared same-source conformer science runtime (${sources.length} source modules).`);
} finally { await bundle.close(); }
