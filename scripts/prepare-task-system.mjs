// Build shared task protocol/reading authorities; no DB, network or scientific execution.
import {rolldown} from 'rolldown';
import {readFile,writeFile,mkdir,copyFile} from 'node:fs/promises';
import {resolve,relative} from 'node:path';
import {createHash} from 'node:crypto';
const root=resolve(import.meta.dirname,'..'),destination=resolve(root,'desktop/task-system');
await mkdir(destination,{recursive:true});
for(const [entry,name]of [['src/task-system/protocol.ts','protocol.cjs'],['src/task-system/reading/index.ts','reading-runtime.cjs']]){
  const bundle=await rolldown({cwd:root,input:resolve(root,entry),platform:'node'});
  try{
    const {output}=await bundle.generate({format:'cjs',sourcemap:false,minify:false,inlineDynamicImports:true});
    if(output.length!==1||output[0].type!=='chunk'||output[0].imports.length)throw Error('Task runtime must be a self-contained CJS bundle');
    const sources=[];for(const path of Object.keys(output[0].modules).filter(path=>!path.startsWith('\0')).sort())sources.push({path:relative(root,path).replaceAll('\\','/'),sha256:createHash('sha256').update(await readFile(path)).digest('hex')});
    await writeFile(resolve(destination,name),'// Generated by prepare-task-system.mjs; single source authority.\n// Sources: '+JSON.stringify(sources)+'\n'+output[0].code.replaceAll('\r\n','\n'),'utf8');
    console.log(`Prepared task runtime ${name} (${sources.length} source modules).`);
  }finally{await bundle.close();}
}
await copyFile(resolve(root,'src/task-system/schema-v1.json'),resolve(destination,'schema-v1.json'));
